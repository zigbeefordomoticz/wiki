SKIP = ("Reserved", "PluginTransport", "VerboseLogging")


def fmt_default(p):
    t, v = p["type"], p["default"]
    if t == "bool":
        return "on" if v else "off"
    if t == "list":
        for k, val in p["list"].items():
            if str(val) == str(v):
                return f"{k}"
        return f"`{v}`"
    if t == "hex":
        return f"`{int(v):04x}`" if isinstance(v, int) else f"`{v}`"
    if v == "":
        return "(empty)"
    return f"`{v}`"


def fmt_restart(r):
    return {0: "", 1: "plugin restart", True: "plugin restart", 2: "coordinator reset", 3: "erase network"}.get(r, str(r))


def values(p):
    if p["type"] == "list":
        return ", ".join(p["list"].keys())
    return ""


def table(params):
    rows = ["| Setting | Shown in the WebUI as | Default | Unit / values | Restart | Notes |",
            "| :------ | :-------------------- | :------ | :------------ | :------ | :---- |"]
    for name, p in params:
        label = LABELS.get(name, "").replace("|", "\\|")
        unit = UNITS.get(name, values(p))
        restart = fmt_restart(p["restart"])
        if name in COORDINATOR_DEPENDENT:
            unit = COORDINATOR_DEPENDENT[name]["unit"]
            restart = COORDINATOR_DEPENDENT[name]["restart"]
        default = "`0`" if name in COORDINATOR_DEPENDENT else fmt_default(p)
        rows.append(f"| `{name}` | {label} | {default} | {unit} | {restart} | {NOTES.get(name, '')} |")
    return "\n".join(rows)


body = []
for cat, v in sorted(SETTINGS.items(), key=lambda x: x[1]["Order"]):
    if cat in SKIP:
        continue
    visible = [(k, p) for k, p in v["param"].items() if not p.get("hidden")]
    if not visible:
        continue
    header = LABELS.get("setting.header." + cat, cat)
    subtitle = LABELS.get("setting.subtitle." + cat, "")
    body.append(f"## {header}\n")
    if subtitle:
        body.append(f"{subtitle}\n")
    basic = [x for x in visible if not x[1]["Advanced"]]
    adv = [x for x in visible if x[1]["Advanced"]]
    if basic:
        body.append("### Parameters\n\n" + table(basic) + "\n")
    if adv:
        body.append("### Advanced parameters\n\n" + table(adv) + "\n")

page = open(out).read()
if GENERATED_MARKER in page:
    intro = page[:page.index(GENERATED_MARKER)]
else:
    # First run on a page without the marker: keep everything before the first generated section.
    first = LABELS.get("setting.header.Services", "Available services")
    intro = page[:page.index("## " + first)]
open(out, "w").write(intro.rstrip() + "\n\n" + GENERATED_MARKER + "\n\n" + "\n".join(body))
